/**
 * electron-builder afterPack hook (Linux).
 *
 * Problem: on modern distributions (Ubuntu 24.04+/26.04) unprivileged user namespaces are
 * restricted by AppArmor (kernel.apparmor_restrict_unprivileged_userns=1) and the shipped
 * chrome-sandbox is not a root-owned 4755 binary. Electron's setuid-sandbox host then aborts
 * with:
 *   FATAL:setuid_sandbox_host.cc(163) The SUID sandbox helper binary was found, but is not
 *   configured correctly...
 * This happens in the native bootstrap *before* any JavaScript runs, so it cannot be handled
 * from main.js. Plain `./Asher` therefore crashes for a normal user.
 *
 * Fix: replace the packaged ELF launcher with a tiny POSIX shell wrapper named `Asher` that
 * runs the real binary (`Asher.bin`). The wrapper:
 *   - uses the OS sandbox when it is usable (chrome-sandbox is root-owned and setuid), else
 *   - falls back to `--no-sandbox` (the manager is a local utility launching a trusted game),
 *   - forwards all user arguments and the environment unchanged.
 * This keeps the documented first-run experience working: `./Asher`.
 *
 * The wrapper is also resilient to transfers that strip the executable bit (Windows-built
 * archives store modes as 0644); it re-execs the real binary via an absolute path resolved
 * from its own location.
 *
 * Hook signature: (context) => Promise<void>
 * context.appOutDir is the unpacked app directory (e.g. .../linux-unpacked).
 */
const fs = require('node:fs');
const path = require('node:path');

const WRAPPER = `#!/bin/sh
# Asher launcher wrapper (generated by afterPack). Runs the real Electron binary.
set -e
SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
BIN="$SELF_DIR/Asher.bin"
if [ ! -x "$BIN" ]; then
  chmod +x "$BIN" 2>/dev/null || true
fi

# Transfers/cross-builds can strip the executable bit from the bundled Host; restore it.
HOST="$SELF_DIR/resources/asher-host/Asher.Host"
if [ -f "$HOST" ] && [ ! -x "$HOST" ]; then
  chmod +x "$HOST" 2>/dev/null || true
fi

# Decide whether Electron's setuid sandbox is usable.
# It needs chrome-sandbox owned by root with mode 4755. Otherwise Electron aborts before JS.
SANDBOX="$SELF_DIR/chrome-sandbox"
if [ -u "$SANDBOX" ] && [ "$(stat -c '%u' "$SANDBOX" 2>/dev/null)" = "0" ]; then
  exec "$BIN" "$@"
fi

# Unprivileged user namespaces disabled/restricted (e.g. Ubuntu 24.04+ AppArmor) -> no sandbox.
exec "$BIN" --no-sandbox "$@"
`;

module.exports = async function afterPack(context) {
  if (context.electronPlatformName !== 'linux') {
    return;
  }

  const appOutDir = context.appOutDir;
  const executableName = context.packager?.executableName || 'Asher';
  const realBinary = path.join(appOutDir, executableName);
  const renamedBinary = path.join(appOutDir, `${executableName}.bin`);
  const wrapperPath = realBinary;

  if (!fs.existsSync(realBinary)) {
    throw new Error(`[afterPack] expected executable not found: ${realBinary}`);
  }

  // If already wrapped (idempotent), skip.
  const head = fs.readFileSync(realBinary).subarray(0, 2).toString('latin1');
  if (head === '#!') {
    return;
  }

  // Rename the ELF binary and install the wrapper in its place.
  fs.renameSync(realBinary, renamedBinary);
  fs.writeFileSync(wrapperPath, WRAPPER, { mode: 0o755 });
  fs.chmodSync(renamedBinary, 0o755);
  fs.chmodSync(wrapperPath, 0o755);

  // Ensure chrome-sandbox is executable too (mode may be lost on cross-builds).
  const sandbox = path.join(appOutDir, 'chrome-sandbox');
  if (fs.existsSync(sandbox)) {
    try {
      fs.chmodSync(sandbox, 0o755);
    } catch {
      // best effort
    }
  }

  console.error(`[afterPack] installed Asher launcher wrapper; real binary -> ${path.basename(renamedBinary)}`);
};

module.exports.WRAPPER = WRAPPER;
